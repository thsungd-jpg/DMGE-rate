/** The BLS wages for a role, or null when there is no honest match: { soc, title, p25, median, p75, year, url }. */
export function anchorFor(field, roleName) {
  const soc = ROLE_SOC[`${field}::${roleName}`];
  const w = soc && WAGES[soc];
  return w ? { soc, ...w, year: WAGE_YEAR, url: WAGE_SOURCE.url } : null;
}
