// What US employees in a matching job earn per hour, to give the Rate step an honest sanity check. Source: US Bureau of Labor Statistics, Occupational
// Employment and Wage Statistics (OEWS), national estimates, May 2025 (https://www.bls.gov/oes/tables.htm; public domain). These are EMPLOYEE wages: they
// say nothing about freelance rates by themselves, which is why the app turns them into "what you'd charge to take home the same" with the user's own
// rate-finder settings (src/utils/rateModels.js, freelanceEquivalent). A role only gets an anchor when a BLS occupation genuinely matches it; many modern
// roles (UGC creator, streamer, tattoo artist, ...) have none and simply get no check.
//
// Refresh (yearly, when BLS publishes the new May tables): download "National" from https://www.bls.gov/oes/tables.htm (oesm25nat.zip -> national_M2025_dl.xlsx),
// read the "All Occupations"-excluded rows for the codes below (columns OCC_CODE, H_PCT25, H_MEDIAN, H_PCT75; the hourly columns can be blank for occupations
// BLS only reports annually, and those are left out rather than guessed), update WAGE_YEAR, then run `node scripts/check-roles.mjs`. BLS refuses scripted
// downloads (HTTP 403), so fetch the file in a normal browser.
